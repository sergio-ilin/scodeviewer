package git

import (
	"regexp"
	"strings"
)

var (
	coAuthorRegex = regexp.MustCompile(`(?i)Co-authored-by:\s*(.*?)(?:<([^>]+)>|$)`)
	aiPrefixRegex = regexp.MustCompile(`(?i)^\[(ai|claude|cursor|copilot|aider|devin|windsurf|gemini|chatgpt)\]`)
)

type AIDetector struct{}

func DetectAI(authorName, authorEmail, message string) (bool, string) {
	nameLower := strings.ToLower(authorName)
	emailLower := strings.ToLower(authorEmail)
	msgLower := strings.ToLower(message)

	// 1. Direct author/email matches
	type checkRule struct {
		term string
		tag  string
	}

	rules := []checkRule{
		{"claude", "Claude"},
		{"cursor", "Cursor"},
		{"copilot", "Copilot"},
		{"windsurf", "Windsurf"},
		{"aider", "Aider"},
		{"devin", "Devin"},
		{"gemini", "Gemini"},
		{"chatgpt", "ChatGPT"},
		{"openai", "OpenAI"},
		{"codeium", "Codeium"},
		{"supermaven", "Supermaven"},
		{"sourcegraph", "Cody"},
		{"v0.dev", "v0"},
		{"bolt.new", "Bolt"},
		{"sweep.dev", "Sweep"},
		{"github-actions[bot]", "Bot"},
	}

	for _, r := range rules {
		if strings.Contains(nameLower, r.term) || strings.Contains(emailLower, r.term) {
			return true, r.tag
		}
	}

	// 2. Commit message prefix or tag
	if match := aiPrefixRegex.FindStringSubmatch(message); len(match) > 1 {
		tag := strings.ToUpper(match[1][:1]) + strings.ToLower(match[1][1:])
		return true, tag
	}

	// 3. Co-authored-by checking
	matches := coAuthorRegex.FindAllStringSubmatch(message, -1)
	for _, m := range matches {
		line := strings.ToLower(strings.Join(m, " "))
		for _, r := range rules {
			if strings.Contains(line, r.term) {
				return true, r.tag
			}
		}
		if strings.Contains(line, "bot") || strings.Contains(line, "ai") {
			return true, "AI"
		}
	}

	// 4. Common commit trailers and phrase indicators
	phrases := []struct {
		phrase string
		tag    string
	}{
		{"generated with cursor", "Cursor"},
		{"generated by cursor", "Cursor"},
		{"claude code", "Claude"},
		{"anthropic", "Claude"},
		{"generated by copilot", "Copilot"},
		{"github copilot", "Copilot"},
		{"assisted-by: aider", "Aider"},
		{"created by devin", "Devin"},
		{"[ai generated]", "AI"},
		{"ai-generated", "AI"},
	}

	for _, p := range phrases {
		if strings.Contains(msgLower, p.phrase) {
			return true, p.tag
		}
	}

	return false, ""
}
